    private val defaultLanguage: AppLanguage = ALL_LANGUAGES.find { it.code == "id-ID" } ?: ALL_LANGUAGES.first()

    private val _currentLanguage = MutableStateFlow(loadLanguage())
    val currentLanguage: StateFlow<AppLanguage> = _currentLanguage.asStateFlow()

    private val _strings = MutableStateFlow(getLocalizedStrings(_currentLanguage.value.code))
    val strings: StateFlow<LocalizedStrings> = _strings.asStateFlow()

    private fun loadLanguage(): AppLanguage {
        val savedCode = prefs.getString("app_language_code", "id-ID") ?: "id-ID"
        return ALL_LANGUAGES.find { it.code.equals(savedCode, ignoreCase = true) } ?: defaultLanguage
    }

    fun setLanguage(language: AppLanguage) {
        _currentLanguage.value = language
        _strings.value = getLocalizedStrings(language.code)
        prefs.edit().putString("app_language_code", language.code).apply()
    }

    fun setLanguageByCode(code: String) {
        val lang = ALL_LANGUAGES.find { it.code.equals(code, ignoreCase = true) } ?: return
        setLanguage(lang)
    }

